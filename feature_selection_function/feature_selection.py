def select_by_statistical_test(X_train, y_train, alpha=0.05):
    """
    Filtra le feature numeriche calcolando il p-value tramite Kruskal-Wallis
    rispetto al target multiclasse.

    Parametri:
    - X_train: DataFrame contenente le feature (solo dati di training)
    - y_train: Series o array con le etichette del target (i capitoli ICD)
    - alpha: livello di significatività (default 0.05)

    Ritorna:
    - selected_features: lista delle feature con p-value <= alpha (discriminanti)
    - dropped_features: lista delle feature con p-value > alpha (non discriminanti)
    - report_df: DataFrame riassuntivo ordinato dal p-value più basso al più alto

    """
    classes = np.unique(y_train)
    p_values = {}
    numeric_cols = X_train.select_dtypes(include=[np.number]).columns

    for col in numeric_cols:
        group_samples = [
            X_train.loc[y_train == c, col].dropna().values for c in classes
        ]
        if all(len(s) > 0 for s in group_samples):
            try:
                _, p_val = kruskal(*group_samples)
                p_values[col] = p_val
            except ValueError:
                p_values[col] = 1.0
        else:
            p_values[col] = 1.0

    p_val_series = pd.Series(p_values)
    selected_numeric = p_val_series[p_val_series <= alpha].index.tolist()
    dropped_features = p_val_series[p_val_series > alpha].index.tolist()

    non_numeric = [c for c in X_train.columns if c not in numeric_cols]
    selected_features = selected_numeric + non_numeric

    report_df = (
        pd.DataFrame({
            "feature": p_val_series.index,
            "p_value": p_val_series.values,
            "selected": p_val_series.values <= alpha,
        })
        .sort_values("p_value")
        .reset_index(drop=True)
    )

    return selected_features, dropped_features, report_df



