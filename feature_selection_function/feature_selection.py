# FUNZIONE 1 - CORRELAZIONE TRA TUTTE LE FEATURE
# ==============================================================

def remove_collinear_features(X_train, y_train=None, threshold=0.90, method="spearman"):
    """
    Rimuove le feature ridondanti (X vs X) su tutte le colonne (continue e binarie 0/1).
    Se due feature hanno |corr| >= threshold, viene mantenuta quella con maggiore
    correlazione con il target y_train (se fornito), altrimenti viene scartata la seconda.

    Parametri:
    - X_train: DataFrame con tutte le feature (dati di training)
    - y_train: Series del target (opzionale per guidare lo scarto)
    - threshold: soglia di correlazione assoluta (default: 0.90)
    - method: 'spearman' (consigliato per dati non gaussiani) o 'pearson'

    Ritorna:
    - selected_features: lista dei nomi delle feature tenute
    - dropped_features: lista dei nomi delle feature eliminate
    - report_df: DataFrame con il log delle coppie eliminate
    """
    # 1. Matrice di correlazione su TUTTE le colonne (numeriche e binarie 0/1)
    corr_matrix = X_train.corr(method=method).abs()

    # 2. Correlazione di ciascuna feature con il target Y (se y_train è presente)
    if y_train is not None:
        target_corr = X_train.apply(lambda col: abs(col.corr(y_train, method=method)))
    else:
        target_corr = None

    # 3. Maschera triangolare superiore (esclude la diagonale e i duplicati simmetrici)
    upper_tri = corr_matrix.where(
        np.triu(np.ones(corr_matrix.shape), k=1).astype(bool)
    )

    to_drop = set()
    pairs_log = []

    # 4. Scansione delle coppie collineari
    for col in upper_tri.columns:
        for row in upper_tri.index:
            val = upper_tri.loc[row, col]
            if pd.notna(val) and val >= threshold:
                # Se una delle due è già stata scartata, salta
                if row in to_drop or col in to_drop:
                    continue

                # Se abbiamo y_train, teniamo la variabile più correlata al target
                if target_corr is not None:
                    if target_corr[row] >= target_corr[col]:
                        drop_feat = col
                        keep_feat = row
                    else:
                        drop_feat = row
                        keep_feat = col
                else:
                    drop_feat = col
                    keep_feat = row

                to_drop.add(drop_feat)
                pairs_log.append({
                    "feature_tenuta": keep_feat,
                    "feature_scartata": drop_feat,
                    "correlazione_inter_feature": val,
                    "corr_target_tenuta": target_corr[keep_feat] if target_corr is not None else None,
                    "corr_target_scartata": target_corr[drop_feat] if target_corr is not None else None
                })

    selected_features = [c for c in X_train.columns if c not in to_drop]
    dropped_features = list(to_drop)
    report_df = pd.DataFrame(pairs_log)

    return selected_features, dropped_features, report_df



