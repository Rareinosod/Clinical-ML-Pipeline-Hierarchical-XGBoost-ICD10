def extract_feature_groups(X_train):
    """
    Separa le feature nei macro-gruppi clinici tenendo conto
    anche delle colonne generate dal One-Hot Encoding.
    """
    all_cols = list(X_train.columns)

    # Prefissi o parole chiave di origine per i vari gruppi
    demo_prefixes = ["age", "gender", "race", "admission_type", "los_hours", "mortality"]
    triage_prefixes = ["temperature", "heartrate", "resprate", "o2sat", "sbp", "dbp", "pain", "acuity"]

    # Seleziona tutte le colonne che iniziano con o contengono i prefissi di gruppo
    demo_cols = [c for c in all_cols if any(c.lower().startswith(p) for p in demo_prefixes)]
    triage_cols = [c for c in all_cols if any(c.lower().startswith(p) for p in triage_prefixes)]

    # Escludiamo gli ID o le flag di servizio
    service_cols = ["hadm_id", "target", "crp_elevated", "outlier", "dbscan", "missing"]

    # Tutto ciò che rimane (e non è demo o triage o servizio) appartiene agli esami del sangue
    blood_cols = [
        c for c in all_cols
        if c not in demo_cols and c not in triage_cols
        and not any(c.lower().startswith(s) or c.lower().endswith(s) for s in service_cols)
    ]

    groups_dict = {
        "demographic": X_train[demo_cols],
        "triage": X_train[triage_cols],
        "blood": X_train[blood_cols],
        "demo_plus_triage": X_train[demo_cols + triage_cols],
        "triage_plus_blood": X_train[triage_cols + blood_cols],
        "all_features": X_train
    }

    return groups_dict